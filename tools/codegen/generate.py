HEADER = "// GENERATED by tools/codegen/generate.py — do not edit by hand.\n// Source: {src}\n"

INT_KEY = re.compile(r"(Ms|Frames)$|^(specVersion|maxSameInARow)$")


# ----------------------------------------------------------------------------- naming
def words(name: str) -> list[str]:
    parts = re.split(r"[.\-_ ]+", name)
    out: list[str] = []
    for p in parts:
        out += re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z0-9]+", p) or [p]
    return [w for w in out if w]


def lower_camel(name: str) -> str:
    w = words(name)
    return w[0].lower() + "".join(x[:1].upper() + x[1:] for x in w[1:])


def upper_camel(name: str) -> str:
    return "".join(x[:1].upper() + x[1:] for x in words(name))


def hex_rgb(value: str) -> str:
    v = value.lstrip("#").upper()
    if not re.fullmatch(r"[0-9A-F]{6}", v):
        raise ValueError(f"bad color {value}")
    return v


def num(v: float) -> str:
    return repr(float(v))


# ----------------------------------------------------------------------------- fonts
WEIGHT_NAMES = {"regular": "Regular", "medium": "Medium", "semibold": "SemiBold", "bold": "Bold",
                "extraBold": "ExtraBold", "black": "Black"}
KT_WEIGHTS = {v: k for k, v in {"Normal": "Regular", "Medium": "Medium", "SemiBold": "SemiBold", "Bold": "Bold",
                                "ExtraBold": "ExtraBold", "Black": "Black"}.items()}


def postscript_name(t: dict, token: dict) -> str:
    """PostScript name of the font file a type token needs, e.g. BarlowCondensed-BlackItalic."""
    weight = WEIGHT_NAMES[token["weight"]]
    if token.get("italic"):
        weight = "Italic" if weight == "Regular" else weight + "Italic"
    return f"{t['fontFamily'][token['family']]}-{weight}"


def font_files() -> list[Path]:
    return sorted(FONTS_DIR.glob("*.ttf"))


def android_font_res(path: Path) -> str:
    return re.sub(r"[^a-z0-9_]", "_", path.stem.lower().replace("-", "_"))


def required_fonts(t: dict) -> set[str]:
    return {postscript_name(t, v) for v in t["typography"].values()}


def gen_fonts_kotlin(t: dict) -> list[str]:
    o = ["object FontTokens {"]
    for key, family in t["fontFamily"].items():
        entries = []
        for f in font_files():
            fam, _, style = f.stem.partition("-")
            if fam != family:
                continue
            italic = style.endswith("Italic")
            weight = style.removesuffix("Italic") or "Regular"
            entries.append(
                f"        Font(R.font.{android_font_res(f)}, FontWeight.{KT_WEIGHTS[weight]}, "
                f"FontStyle.{'Italic' if italic else 'Normal'}),"
            )
        o.append(f"    val {upper_camel(key)} = FontFamily(")
        o += entries
        o.append("    )")
    o.append("}\n")
    return o


# ----------------------------------------------------------------------------- tokens
def gen_tokens_swift(t: dict) -> str:
    o = [HEADER.format(src="shared/design-tokens/tokens.json"), "import CoreGraphics\n"]
    o.append("/// sRGB color pair for light and dark appearance (0xRRGGBB).")
    o.append("public struct TokenColor: Sendable, Hashable {\n    public let light: UInt32\n    public let dark: UInt32\n}\n")
    o.append("public enum ColorTokens {")
    for k, v in t["color"].items():
        o.append(f"    public static let {lower_camel(k)} = TokenColor(light: 0x{hex_rgb(v['light'])}, dark: 0x{hex_rgb(v['dark'])})")
    o.append("}\n")

    o.append("public struct TokenGradient: Sendable {\n    public let angleDegrees: Double\n    public let stops: [TokenColor]\n}\n")
    o.append("public enum GradientTokens {")
    for k, v in t["gradient"].items():
        stops = ", ".join(f"ColorTokens.{lower_camel(s)}" for s in v["stops"])
        o.append(f"    public static let {lower_camel(k)} = TokenGradient(angleDegrees: {num(v['angle'])}, stops: [{stops}])")
    o.append("}\n")

    o.append("public enum SpacingTokens {")
    for k, v in t["spacing"].items():
        o.append(f"    public static let {lower_camel(k)}: CGFloat = {num(v)}")
    o.append("}\n")
    o.append("public enum RadiusTokens {")
    for k, v in t["radius"].items():
        o.append(f"    public static let {lower_camel(k)}: CGFloat = {num(v)}")
    o.append("}\n")

    o.append("public enum TokenFontWeight: String, Sendable { case regular, medium, semibold, bold, extraBold, black }")
    o.append("public enum TokenFontFamily: String, Sendable { case display, text }")
    o.append("/// Dynamic Type text style the token scales with (sizes match Apple's default text styles).")
    o.append("public enum TokenTextStyle: String, Sendable { case largeTitle, title, title2, title3, headline, body, subheadline, footnote, caption, caption2 }\n")
    o.append("public struct TypeToken: Sendable {")
    o.append("    public let size: CGFloat\n    public let lineHeight: CGFloat\n    public let weight: TokenFontWeight")
    o.append("    public let family: TokenFontFamily\n    public let italic: Bool\n    /// PostScript name of the bundled font file (Resources/Fonts).")
    o.append("    public let fontName: String\n    public let textStyle: TokenTextStyle\n    public let tracking: CGFloat\n    public let uppercase: Bool\n    public let minSize: CGFloat?\n}\n")
    o.append("public enum TypographyTokens {")
    o.append("    /// Every bundled font file (registered at launch by `PushlyFonts.register()`).")
    names = ", ".join(json.dumps(f.stem) for f in font_files())
    o.append(f"    public static let bundledFonts: [String] = [{names}]")
    for k, v in t["typography"].items():
        ms = num(v["minSize"]) if "minSize" in v else "nil"
        o.append(
            f"    public static let {lower_camel(k)} = TypeToken(size: {num(v['size'])}, lineHeight: {num(v['lineHeight'])}, "
            f"weight: .{v['weight']}, family: .{v['family']}, italic: {str(v.get('italic', False)).lower()}, "
            f"fontName: \"{postscript_name(t, v)}\", textStyle: .{v['textStyle']}, tracking: {num(v.get('tracking', 0))}, "
            f"uppercase: {str(v.get('uppercase', False)).lower()}, minSize: {ms})"
        )
    o.append("}\n")

    o.append("public enum MotionTokens {")
    for k, v in t["motion"].items():
        o.append(f"    public static let {lower_camel(k)}Seconds: Double = {v['ms'] / 1000!r}")
    o.append("}\n")
    o.append(f"public enum TouchTarget {{\n    public static let minimum: CGFloat = {num(t['touchTarget']['iosPt'])}\n}}")
    return "\n".join(o) + "\n"


def gen_tokens_kotlin(t: dict) -> str:
    o = [HEADER.format(src="shared/design-tokens/tokens.json"), "package app.pushly.core.designsystem.generated\n"]
    o.append("import androidx.compose.ui.graphics.Color")
    o.append("import androidx.compose.ui.text.font.Font")
    o.append("import androidx.compose.ui.text.font.FontFamily")
    o.append("import androidx.compose.ui.text.font.FontStyle")
    o.append("import androidx.compose.ui.text.font.FontWeight")
    o.append("import androidx.compose.ui.unit.Dp")
    o.append("import androidx.compose.ui.unit.TextUnit")
    o.append("import androidx.compose.ui.unit.dp")
    o.append("import androidx.compose.ui.unit.sp")
    o.append("import app.pushly.core.designsystem.R\n")
    o.append("data class TokenColor(val light: Color, val dark: Color)\n")
    o.append("object ColorTokens {")
    for k, v in t["color"].items():
        o.append(f"    val {upper_camel(k)} = TokenColor(light = Color(0xFF{hex_rgb(v['light'])}), dark = Color(0xFF{hex_rgb(v['dark'])}))")
    o.append("}\n")
    o.append("data class TokenGradient(val angleDegrees: Float, val stops: List<TokenColor>)\n")
    o.append("object GradientTokens {")
    for k, v in t["gradient"].items():
        stops = ", ".join(f"ColorTokens.{upper_camel(s)}" for s in v["stops"])
        o.append(f"    val {upper_camel(k)} = TokenGradient(angleDegrees = {float(v['angle'])}f, stops = listOf({stops}))")
    o.append("}\n")
    o.append("object SpacingTokens {")
    for k, v in t["spacing"].items():
        o.append(f"    val {upper_camel(k)}: Dp = {v}.dp")
    o.append("}\n")
    o.append("object RadiusTokens {")
    for k, v in t["radius"].items():
        o.append(f"    val {upper_camel(k)}: Dp = {v}.dp")
    o.append("}\n")
    o.append("enum class TokenFontWeight { Regular, Medium, Semibold, Bold, ExtraBold, Black }")
    o.append("enum class TokenFontFamily { Display, Text }\n")
    o += gen_fonts_kotlin(t)
    o.append("data class TypeToken(")
    o.append("    val size: TextUnit,\n    val lineHeight: TextUnit,\n    val weight: TokenFontWeight,\n    val family: TokenFontFamily,\n    val italic: Boolean,")
    o.append("    val trackingEm: Float,\n    val uppercase: Boolean,\n    val minSize: TextUnit?,\n)\n")
    o.append("object TypographyTokens {")
    for k, v in t["typography"].items():
        ms = f"{v['minSize']}.sp" if "minSize" in v else "null"
        o.append(
            f"    val {upper_camel(k)} = TypeToken(size = {v['size']}.sp, lineHeight = {v['lineHeight']}.sp, "
            f"weight = TokenFontWeight.{upper_camel(v['weight'])}, family = TokenFontFamily.{upper_camel(v['family'])}, "
            f"italic = {str(v.get('italic', False)).lower()}, "
            f"trackingEm = {float(v.get('tracking', 0))}f, uppercase = {str(v.get('uppercase', False)).lower()}, minSize = {ms})"
        )
    o.append("}\n")
    o.append("object MotionTokens {")
    for k, v in t["motion"].items():
        o.append(f"    const val {re.sub(r'(?<!^)(?=[A-Z])', '_', upper_camel(k)).upper()}_MS: Int = {v['ms']}")
    o.append("}\n")
    o.append(f"object TouchTarget {{\n    val Minimum: Dp = {t['touchTarget']['androidDp']}.dp\n}}")
    return "\n".join(o) + "\n"


# ----------------------------------------------------------------------------- rep spec
def swift_value(key: str, v):
    if isinstance(v, bool):
        return "Bool", str(v).lower()
    if isinstance(v, (int, float)):
        if INT_KEY.search(key):
            if float(v) != int(v):
                raise ValueError(f"{key} must be an integer")
            return "Int", str(int(v))
        return "Double", num(v)
    if isinstance(v, str):
        return "String", json.dumps(v)
    if isinstance(v, list) and len(v) == 2 and all(isinstance(x, (int, float)) for x in v):
        return "ClosedRange<Double>", f"{num(v[0])}...{num(v[1])}"
    raise ValueError(f"unsupported value for {key}: {v!r}")


def kotlin_value(key: str, v):
    if isinstance(v, bool):
        return "Boolean", str(v).lower(), True
    if isinstance(v, (int, float)):
        if INT_KEY.search(key):
            return "Int", str(int(v)), True
        return "Double", num(v), True
    if isinstance(v, str):
        return "String", json.dumps(v), True
    if isinstance(v, list) and len(v) == 2:
        return "ClosedFloatingPointRange<Double>", f"{num(v[0])}..{num(v[1])}", False
    raise ValueError(f"unsupported value for {key}: {v!r}")


def gen_spec_swift(name: str, spec: dict, src: str) -> str:
    o = [HEADER.format(src=src)]

    def emit(d: dict, indent: int):
        pad = "    " * indent
        for k, v in d.items():
            if isinstance(v, dict):
                o.append(f"{pad}public enum {upper_camel(k)} {{")
                emit(v, indent + 1)
                o.append(f"{pad}}}")
            else:
                typ, val = swift_value(k, v)
                o.append(f"{pad}public static let {lower_camel(k)}: {typ} = {val}")

    o.append(f"public enum {name} {{")
    emit(spec, 1)
    o.append("}")
    return "\n".join(o) + "\n"


def gen_spec_kotlin(name: str, spec: dict, src: str) -> str:
    o = [HEADER.format(src=src), "package app.pushly.engine.rep.generated\n"]

    def const_name(k: str) -> str:
        return re.sub(r"(?<!^)(?=[A-Z])", "_", upper_camel(k)).upper()

    def emit(d: dict, indent: int):
        pad = "    " * indent
        for k, v in d.items():
            if isinstance(v, dict):
                o.append(f"{pad}object {upper_camel(k)} {{")
                emit(v, indent + 1)
                o.append(f"{pad}}}")
            else:
                typ, val, is_const = kotlin_value(k, v)
                if is_const:
                    o.append(f"{pad}const val {const_name(k)}: {typ} = {val}")
                else:
                    o.append(f"{pad}val {const_name(k)}: {typ} = {val}")

    o.append(f"object {name} {{")
    emit(spec, 1)
    o.append("}")
    return "\n".join(o) + "\n"


# ----------------------------------------------------------------------------- workouts (D-069)
def swift_str(v: str) -> str:
    return json.dumps(v, ensure_ascii=False)


def kt_res_name(preset_id: str, field: str) -> str:
    return "workout_preset_" + re.sub(r"[^a-z0-9]+", "_", preset_id.lower()) + "_" + field


def xml_escape(v: str) -> str:
    return (v.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("'", "\\'")
            .replace('"', '\\"'))


def gen_workouts_swift(presets: list[dict], src: str) -> str:
    o = [HEADER.format(src=src), "import Foundation\n", "extension Workout {", "    /// Built-in workouts, in display order.",
         "    public static let presets: [Workout] = ["]
    for p in presets:
        sets = ", ".join(f"WorkoutSet(kind: .{x['kind']}, target: {x['target']}, restS: {x['restS']})" for x in p["sets"])
        every = p.get("everyS")
        o.append(f"        Workout(id: {swift_str(p['id'])}, name: String(localized: {swift_str(p['name'])}),")
        o.append(f"                description: String(localized: {swift_str(p.get('description', ''))}),")
        o.append(f"                everyS: {every if every is not None else 'nil'}, isPreset: true,")
        o.append(f"                sets: [{sets}]),")
    o += ["    ]", "}"]
    return "\n".join(o) + "\n"


def gen_workouts_kotlin(presets: list[dict], src: str) -> str:
    o = [HEADER.format(src=src), "package app.pushly.feature.wakeflow.generated\n",
         "import app.pushly.feature.wakeflow.R", "import app.pushly.feature.wakeflow.SetKind",
         "import app.pushly.feature.wakeflow.WorkoutSet\n",
         "/** A built-in workout; name and description are string resources (generated workout_presets.xml). */",
         "data class WorkoutPreset(val id: String, val nameRes: Int, val descriptionRes: Int, val everyS: Int?, val sets: List<WorkoutSet>)\n",
         "object WorkoutPresets {", "    val all: List<WorkoutPreset> = listOf("]
    for p in presets:
        sets = ", ".join(f"WorkoutSet(SetKind.{x['kind'].upper()}, {x['target']}, {x['restS']})" for x in p["sets"])
        every = p.get("everyS")
        o.append(f"        WorkoutPreset(\"{p['id']}\", R.string.{kt_res_name(p['id'], 'name')}, "
                 f"R.string.{kt_res_name(p['id'], 'description')}, {every if every is not None else 'null'},")
        o.append(f"            listOf({sets})),")
    o += ["    )", "}"]
    return "\n".join(o) + "\n"


def gen_workout_strings(presets: list[dict], src: str) -> str:
    o = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- GENERATED by tools/codegen/generate.py from {src} — do not edit. -->",
         "<resources>"]
    for p in presets:
        o.append(f'    <string name="{kt_res_name(p["id"], "name")}">{xml_escape(p["name"])}</string>')
        o.append(f'    <string name="{kt_res_name(p["id"], "description")}">{xml_escape(p.get("description", ""))}</string>')
    o.append("</resources>")
    return "\n".join(o) + "\n"


# ----------------------------------------------------------------------------- main
def outputs() -> dict[Path, str | bytes]:
    files: dict[Path, str | bytes] = {}
    tokens = json.loads(TOKENS.read_text())
    available = {f.stem for f in font_files()}
    missing = required_fonts(tokens) - available
    if missing:
        raise ValueError(f"typography tokens need font files missing from {FONTS_DIR}: {sorted(missing)}")
    for f in font_files():
        files[IOS_FONTS_DIR / f.name] = f.read_bytes()
        files[KT_FONTS_DIR / f"{android_font_res(f)}.ttf"] = f.read_bytes()
    files[IOS_TOKENS] = gen_tokens_swift(tokens)
    files[KT_TOKENS] = gen_tokens_kotlin(tokens)
    for path in sorted(SPEC_DIR.glob("*.yaml")):
        spec = yaml.safe_load(path.read_text())
        name = upper_camel(f"{spec['exerciseType']} spec v{spec['specVersion']}")  # PushupSpecV2
        src = str(path.relative_to(ROOT))
        files[IOS_SPEC_DIR / f"{name}.swift"] = gen_spec_swift(name, spec, src)
        files[KT_SPEC_DIR / f"{name}.kt"] = gen_spec_kotlin(name, spec, src)
    presets = json.loads(WORKOUTS.read_text())["presets"]
    src = str(WORKOUTS.relative_to(ROOT))
    files[IOS_WORKOUTS] = gen_workouts_swift(presets, src)
    files[KT_WORKOUTS] = gen_workouts_kotlin(presets, src)
    files[KT_WORKOUT_STRINGS] = gen_workout_strings(presets, src)
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            current = path.read_bytes() if path.exists() else None
            if current != (content if isinstance(content, bytes) else content.encode()):
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if isinstance(content, bytes):
                path.write_bytes(content)
            else:
                path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Generated files are out of date — run python3 tools/codegen/generate.py:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
