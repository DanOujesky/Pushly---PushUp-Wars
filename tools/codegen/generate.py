#!/usr/bin/env python3
"""Pushly code generator (roadmap P0-05).

Generates platform code from the shared sources of truth:
  shared/design-tokens/tokens.json      -> Swift + Kotlin design tokens
  shared/rep-engine-spec/*.yaml         -> Swift + Kotlin rep-engine constants

Usage:
  python3 tools/codegen/generate.py           # write generated files
  python3 tools/codegen/generate.py --check   # exit 1 if generated files are out of date (CI)

JSON Schema -> model generation is added when the first contract schema lands (roadmap P2-09).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
TOKENS = ROOT / "shared/design-tokens/tokens.json"
SPEC_DIR = ROOT / "shared/rep-engine-spec"

IOS_TOKENS = ROOT / "ios/Packages/DesignSystem/Sources/DesignSystem/Generated/DesignTokens.swift"
KT_TOKENS = ROOT / "android/core/designsystem/src/main/kotlin/app/pushly/core/designsystem/generated/DesignTokens.kt"
IOS_SPEC_DIR = ROOT / "ios/Packages/RepEngine/Sources/RepEngine/Generated"
KT_SPEC_DIR = ROOT / "android/engine/rep/src/main/kotlin/app/pushly/engine/rep/generated"

HEADER = "// GENERATED by tools/codegen/generate.py — do not edit by hand.\n// Source: {src}\n"

INT_KEY = re.compile(r"(Ms|Frames)$|^(specVersion|maxSameInARow)$")


# ----------------------------------------------------------------------------- naming
def words(name: str) -> list[str]:
    parts = re.split(r"[.\-_ ]+", name)
    out: list[str] = []
    for p in parts:
        out += re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z0-9]+", p) or [p]
    return [w for w in out if w]


def lower_camel(name: str) -> str:
    w = words(name)
    return w[0].lower() + "".join(x[:1].upper() + x[1:] for x in w[1:])


def upper_camel(name: str) -> str:
    return "".join(x[:1].upper() + x[1:] for x in words(name))


def hex_rgb(value: str) -> str:
    v = value.lstrip("#").upper()
    if not re.fullmatch(r"[0-9A-F]{6}", v):
        raise ValueError(f"bad color {value}")
    return v


def num(v: float) -> str:
    return repr(float(v))


# ----------------------------------------------------------------------------- tokens
def gen_tokens_swift(t: dict) -> str:
    o = [HEADER.format(src="shared/design-tokens/tokens.json"), "import CoreGraphics\n"]
    o.append("/// sRGB color pair for light and dark appearance (0xRRGGBB).")
    o.append("public struct TokenColor: Sendable, Hashable {\n    public let light: UInt32\n    public let dark: UInt32\n}\n")
    o.append("public enum ColorTokens {")
    for k, v in t["color"].items():
        o.append(f"    public static let {lower_camel(k)} = TokenColor(light: 0x{hex_rgb(v['light'])}, dark: 0x{hex_rgb(v['dark'])})")
    o.append("}\n")

    o.append("public struct TokenGradient: Sendable {\n    public let angleDegrees: Double\n    public let stops: [TokenColor]\n}\n")
    o.append("public enum GradientTokens {")
    for k, v in t["gradient"].items():
        stops = ", ".join(f"ColorTokens.{lower_camel(s)}" for s in v["stops"])
        o.append(f"    public static let {lower_camel(k)} = TokenGradient(angleDegrees: {num(v['angle'])}, stops: [{stops}])")
    o.append("}\n")

    o.append("public enum SpacingTokens {")
    for k, v in t["spacing"].items():
        o.append(f"    public static let {lower_camel(k)}: CGFloat = {num(v)}")
    o.append("}\n")
    o.append("public enum RadiusTokens {")
    for k, v in t["radius"].items():
        o.append(f"    public static let {lower_camel(k)}: CGFloat = {num(v)}")
    o.append("}\n")

    o.append("public enum TokenFontWeight: String, Sendable { case regular, medium, semibold, bold, extraBold }")
    o.append("public enum TokenFontFamily: String, Sendable { case display, system }")
    o.append("/// Dynamic Type text style the token scales with (sizes match Apple's default text styles).")
    o.append("public enum TokenTextStyle: String, Sendable { case largeTitle, title, title2, headline, body, subheadline, caption, caption2 }\n")
    o.append("public struct TypeToken: Sendable {")
    o.append("    public let size: CGFloat\n    public let lineHeight: CGFloat\n    public let weight: TokenFontWeight")
    o.append("    public let family: TokenFontFamily\n    public let textStyle: TokenTextStyle\n    public let tracking: CGFloat\n    public let uppercase: Bool\n    public let minSize: CGFloat?\n}\n")
    o.append("public enum TypographyTokens {")
    o.append(f"    public static let displayFontName = \"{t['fontFamily']['display']}\"")
    for k, v in t["typography"].items():
        ms = num(v["minSize"]) if "minSize" in v else "nil"
        o.append(
            f"    public static let {lower_camel(k)} = TypeToken(size: {num(v['size'])}, lineHeight: {num(v['lineHeight'])}, "
            f"weight: .{v['weight']}, family: .{v['family']}, textStyle: .{v['textStyle']}, tracking: {num(v.get('tracking', 0))}, "
            f"uppercase: {str(v.get('uppercase', False)).lower()}, minSize: {ms})"
        )
    o.append("}\n")

    o.append("public enum MotionTokens {")
    for k, v in t["motion"].items():
        o.append(f"    public static let {lower_camel(k)}Seconds: Double = {v['ms'] / 1000!r}")
    o.append("}\n")
    o.append(f"public enum TouchTarget {{\n    public static let minimum: CGFloat = {num(t['touchTarget']['iosPt'])}\n}}")
    return "\n".join(o) + "\n"


def gen_tokens_kotlin(t: dict) -> str:
    o = [HEADER.format(src="shared/design-tokens/tokens.json"), "package app.pushly.core.designsystem.generated\n"]
    o.append("import androidx.compose.ui.graphics.Color")
    o.append("import androidx.compose.ui.unit.Dp")
    o.append("import androidx.compose.ui.unit.TextUnit")
    o.append("import androidx.compose.ui.unit.dp")
    o.append("import androidx.compose.ui.unit.sp\n")
    o.append("data class TokenColor(val light: Color, val dark: Color)\n")
    o.append("object ColorTokens {")
    for k, v in t["color"].items():
        o.append(f"    val {upper_camel(k)} = TokenColor(light = Color(0xFF{hex_rgb(v['light'])}), dark = Color(0xFF{hex_rgb(v['dark'])}))")
    o.append("}\n")
    o.append("data class TokenGradient(val angleDegrees: Float, val stops: List<TokenColor>)\n")
    o.append("object GradientTokens {")
    for k, v in t["gradient"].items():
        stops = ", ".join(f"ColorTokens.{upper_camel(s)}" for s in v["stops"])
        o.append(f"    val {upper_camel(k)} = TokenGradient(angleDegrees = {float(v['angle'])}f, stops = listOf({stops}))")
    o.append("}\n")
    o.append("object SpacingTokens {")
    for k, v in t["spacing"].items():
        o.append(f"    val {upper_camel(k)}: Dp = {v}.dp")
    o.append("}\n")
    o.append("object RadiusTokens {")
    for k, v in t["radius"].items():
        o.append(f"    val {upper_camel(k)}: Dp = {v}.dp")
    o.append("}\n")
    o.append("enum class TokenFontWeight { Regular, Medium, Semibold, Bold, ExtraBold }")
    o.append("enum class TokenFontFamily { Display, System }\n")
    o.append("data class TypeToken(")
    o.append("    val size: TextUnit,\n    val lineHeight: TextUnit,\n    val weight: TokenFontWeight,\n    val family: TokenFontFamily,")
    o.append("    val trackingEm: Float,\n    val uppercase: Boolean,\n    val minSize: TextUnit?,\n)\n")
    o.append("object TypographyTokens {")
    o.append(f"    const val DISPLAY_FONT_NAME = \"{t['fontFamily']['display']}\"")
    for k, v in t["typography"].items():
        ms = f"{v['minSize']}.sp" if "minSize" in v else "null"
        o.append(
            f"    val {upper_camel(k)} = TypeToken(size = {v['size']}.sp, lineHeight = {v['lineHeight']}.sp, "
            f"weight = TokenFontWeight.{upper_camel(v['weight'])}, family = TokenFontFamily.{upper_camel(v['family'])}, "
            f"trackingEm = {float(v.get('tracking', 0))}f, uppercase = {str(v.get('uppercase', False)).lower()}, minSize = {ms})"
        )
    o.append("}\n")
    o.append("object MotionTokens {")
    for k, v in t["motion"].items():
        o.append(f"    const val {re.sub(r'(?<!^)(?=[A-Z])', '_', upper_camel(k)).upper()}_MS: Int = {v['ms']}")
    o.append("}\n")
    o.append(f"object TouchTarget {{\n    val Minimum: Dp = {t['touchTarget']['androidDp']}.dp\n}}")
    return "\n".join(o) + "\n"


# ----------------------------------------------------------------------------- rep spec
def swift_value(key: str, v):
    if isinstance(v, bool):
        return "Bool", str(v).lower()
    if isinstance(v, (int, float)):
        if INT_KEY.search(key):
            if float(v) != int(v):
                raise ValueError(f"{key} must be an integer")
            return "Int", str(int(v))
        return "Double", num(v)
    if isinstance(v, str):
        return "String", json.dumps(v)
    if isinstance(v, list) and len(v) == 2 and all(isinstance(x, (int, float)) for x in v):
        return "ClosedRange<Double>", f"{num(v[0])}...{num(v[1])}"
    raise ValueError(f"unsupported value for {key}: {v!r}")


def kotlin_value(key: str, v):
    if isinstance(v, bool):
        return "Boolean", str(v).lower(), True
    if isinstance(v, (int, float)):
        if INT_KEY.search(key):
            return "Int", str(int(v)), True
        return "Double", num(v), True
    if isinstance(v, str):
        return "String", json.dumps(v), True
    if isinstance(v, list) and len(v) == 2:
        return "ClosedFloatingPointRange<Double>", f"{num(v[0])}..{num(v[1])}", False
    raise ValueError(f"unsupported value for {key}: {v!r}")


def gen_spec_swift(name: str, spec: dict, src: str) -> str:
    o = [HEADER.format(src=src)]

    def emit(d: dict, indent: int):
        pad = "    " * indent
        for k, v in d.items():
            if isinstance(v, dict):
                o.append(f"{pad}public enum {upper_camel(k)} {{")
                emit(v, indent + 1)
                o.append(f"{pad}}}")
            else:
                typ, val = swift_value(k, v)
                o.append(f"{pad}public static let {lower_camel(k)}: {typ} = {val}")

    o.append(f"public enum {name} {{")
    emit(spec, 1)
    o.append("}")
    return "\n".join(o) + "\n"


def gen_spec_kotlin(name: str, spec: dict, src: str) -> str:
    o = [HEADER.format(src=src), "package app.pushly.engine.rep.generated\n"]

    def const_name(k: str) -> str:
        return re.sub(r"(?<!^)(?=[A-Z])", "_", upper_camel(k)).upper()

    def emit(d: dict, indent: int):
        pad = "    " * indent
        for k, v in d.items():
            if isinstance(v, dict):
                o.append(f"{pad}object {upper_camel(k)} {{")
                emit(v, indent + 1)
                o.append(f"{pad}}}")
            else:
                typ, val, is_const = kotlin_value(k, v)
                if is_const:
                    o.append(f"{pad}const val {const_name(k)}: {typ} = {val}")
                else:
                    o.append(f"{pad}val {const_name(k)}: {typ} = {val}")

    o.append(f"object {name} {{")
    emit(spec, 1)
    o.append("}")
    return "\n".join(o) + "\n"


# ----------------------------------------------------------------------------- main
def outputs() -> dict[Path, str]:
    files: dict[Path, str] = {}
    tokens = json.loads(TOKENS.read_text())
    files[IOS_TOKENS] = gen_tokens_swift(tokens)
    files[KT_TOKENS] = gen_tokens_kotlin(tokens)
    for path in sorted(SPEC_DIR.glob("*.yaml")):
        spec = yaml.safe_load(path.read_text())
        name = upper_camel(f"{spec['exerciseType']} spec v{spec['specVersion']}")  # PushupSpecV1
        src = str(path.relative_to(ROOT))
        files[IOS_SPEC_DIR / f"{name}.swift"] = gen_spec_swift(name, spec, src)
        files[KT_SPEC_DIR / f"{name}.kt"] = gen_spec_kotlin(name, spec, src)
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Generated files are out of date — run python3 tools/codegen/generate.py:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
